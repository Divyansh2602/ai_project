"""Security / Provenance Agent (Phase 5.1 + 5.4).

Two provenance checks that complement the statistical forensic agents:

  - **C2PA content credentials** — reads the embedded C2PA manifest (Adobe CAI
    standard). A cryptographically VALID manifest is the strongest possible
    authenticity signal (fast-tracked to Authentic by the decision engine);
    an INVALID one means the file was modified after signing.
  - **Invisible watermark** — decodes the `invisible-watermark` DWT-DCT channel
    and compares against known AI-generator payloads (Stable Diffusion embeds
    "StableDiffusionV1" / "SDV2" by default). A match is near-proof of AI origin.

Confidence semantics follow base.py (1.0 = authentic). When *neither* signal is
present the agent reports confidence=None so the decision engine excludes it
from the weighted average instead of dragging the score toward 0.5.
"""
import os

from .base import AgentOutput, Finding

AGENT_NAME = "security"

# Payloads that generators embed via invisible-watermark (dwtDct, 'bytes').
KNOWN_WATERMARKS = {
    b"StableDiffusionV1": "Stable Diffusion v1.x",
    b"SDV2": "Stable Diffusion v2.x",
}

# c2pa validation states that count as cryptographically valid.
_VALID_STATES = {"valid", "trusted"}


def _check_c2pa(file_path: str, out: AgentOutput) -> str:
    """Returns 'valid', 'invalid', or 'absent'."""
    try:
        from c2pa import Reader
    except Exception as exc:
        out.add(Finding("c2pa_manifest", "error", f"c2pa SDK unavailable: {exc}"))
        return "absent"

    reader = None
    try:
        reader = Reader(file_path)
    except Exception as exc:
        msg = str(exc)
        if "ManifestNotFound" in msg or "not found" in msg.lower() or "no claim" in msg.lower():
            out.add(Finding("c2pa_manifest", "ok",
                            "No C2PA content credentials embedded (typical for most media)."))
        else:
            out.add(Finding("c2pa_manifest", "skipped", f"C2PA read failed: {msg[:200]}"))
        return "absent"

    try:
        state = ""
        try:
            state = str(reader.get_validation_state() or "").lower()
        except Exception:
            pass

        info = {}
        try:
            import json as _json
            store = _json.loads(reader.json())
            active = store.get("manifests", {}).get(store.get("active_manifest", ""), {})
            info = {
                "claim_generator": active.get("claim_generator")
                or (active.get("claim_generator_info") or [{}])[0].get("name"),
                "issuer": (active.get("signature_info") or {}).get("issuer"),
                "signed_at": (active.get("signature_info") or {}).get("time"),
                "title": active.get("title"),
            }
        except Exception:
            pass
        out.extra["c2pa"] = {"validation_state": state, **{k: v for k, v in info.items() if v}}

        if any(s in state for s in _VALID_STATES) and "invalid" not in state:
            issuer = info.get("issuer") or "unknown issuer"
            out.add(Finding("c2pa_manifest", "ok",
                            f"VALID C2PA manifest — signed by {issuer}, "
                            f"generator: {info.get('claim_generator') or 'n/a'}.", score=0.98))
            return "valid"

        out.add(Finding("c2pa_manifest", "suspicious",
                        f"C2PA manifest present but validation state is '{state or 'unknown'}' — "
                        "file was likely modified after signing.", score=0.1))
        return "invalid"
    finally:
        try:
            reader.close()
        except Exception:
            pass


def _check_watermark(file_path: str, out: AgentOutput) -> str | None:
    """Returns the generator name on a match, else None."""
    try:
        import cv2
        from imwatermark import WatermarkDecoder
    except Exception as exc:
        out.add(Finding("invisible_watermark", "error", f"decoder unavailable: {exc}"))
        return None

    img = cv2.imread(file_path)
    if img is None:
        out.add(Finding("invisible_watermark", "skipped", "Not decodable as an image."))
        return None
    if min(img.shape[0], img.shape[1]) < 256:
        out.add(Finding("invisible_watermark", "skipped", "Image too small for DWT-DCT decode."))
        return None

    for payload, generator in KNOWN_WATERMARKS.items():
        try:
            decoder = WatermarkDecoder("bytes", len(payload) * 8)
            decoded = bytes(decoder.decode(img, "dwtDct"))
            if decoded == payload:
                out.add(Finding("invisible_watermark", "suspicious",
                                f"Invisible watermark '{payload.decode()}' found — "
                                f"image was generated by {generator}.", score=0.02))
                out.extra["watermark_generator"] = generator
                return generator
        except Exception:
            continue

    out.add(Finding("invisible_watermark", "ok", "No known AI-generator watermark detected."))
    return None


def run(file_path: str) -> dict:
    out = AgentOutput(agent=AGENT_NAME)
    if not os.path.exists(file_path):
        out.add(Finding("file", "error", "file not found"))
        out.confidence = 0.5
        return out.dict()

    c2pa_state = _check_c2pa(file_path, out)

    ext = os.path.splitext(file_path)[1].lower()
    watermark_hit = None
    if ext in (".jpg", ".jpeg", ".png", ".webp", ".bmp"):
        watermark_hit = _check_watermark(file_path, out)

    # Confidence: provenance signals are near-decisive when present.
    if watermark_hit:
        out.confidence = 0.05
    elif c2pa_state == "invalid":
        out.confidence = 0.1
    elif c2pa_state == "valid":
        out.confidence = 0.97
        out.extra["fast_track_authentic"] = True

    d = out.dict()
    if not watermark_hit and c2pa_state == "absent":
        # No provenance data either way — don't bias the weighted average.
        d["confidence"] = None
    return d
